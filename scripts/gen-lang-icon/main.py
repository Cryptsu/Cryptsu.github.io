import json
import os
import sys
from pathlib import Path

os.chdir(os.path.dirname(__file__))

CONFIGS = {
    "gen_icon_variables": False,
    "gen_icon_jsx_elements": False,
}

requirements = [
    Path("./reflector-supports.json"),
    Path("../../node_modules/devicon/devicon.json"),
    Path("../../node_modules/devicon/icons/"),
]

for path in requirements:
    if not os.path.exists(path):
        raise FileNotFoundError(f'Required path "{path}" not exist.')

def print_usage():
    print(f"usage: {sys.argv[0]} [--gen-icon-var] [--gen-icon-jsx]", file=sys.stderr)
    sys.exit(-1)

if len(sys.argv) == 1:
    CONFIGS["gen_icon_variables"] = True
elif len(sys.argv) != 2:
    print_usage()
elif sys.argv[1] == "--gen-icon-var":
    CONFIGS["gen_icon_variables"] = True
elif sys.argv[1] == "--gen-icon-jsx":
    CONFIGS["gen_icon_jsx_elements"] = True
else:
    print_usage()

supported_languages = json.load(open(requirements[0], "r"))
icons_map           = json.load(open(requirements[1], "r"))
svg_icons_dirpath   = requirements[2]

def find_icon_info(icon_name):
    for icon_info in icons_map:
        if icon_info["name"] == icon_name:
            return icon_info
    assert False

def icon_to_jsx(icon_name):
    return icon_name[0].upper() + icon_name[1:] + "Icon"

def print_autogen_header():
    info = f"""Auto generated by {sys.argv[0]} {sys.argv[1] if len(sys.argv) >= 2 else ""}"""
    ndash = len(info) + 2

    print(f"""
/* {"-" * ndash}
 *  {info}
 * {"-" * ndash}
 */
    """.strip(' ').strip('\n'))

def gen_icon_variables():
    def check_and_print(icon_name, svg_version):
        svg_iconpath = svg_icons_dirpath / icon_name / f"{icon_name}-{svg_version}.svg"
        if not os.path.exists(svg_iconpath):
            return False

        jsx_obj_name = icon_to_jsx(icon_name)
        print(f"""
export {{ default as {jsx_obj_name} }} from \"devicon/icons/{icon_name}/{icon_name}-{svg_version}.svg\";
        """.strip(' ').strip('\n'))
        return True

    print_autogen_header()

    for language in supported_languages:
        lang_info = supported_languages[language]
        if 'devicon_name' not in lang_info:
            continue

        # aliases = lang_info['alias']
        icon_name = lang_info['devicon_name']
        icon_info = find_icon_info(icon_name)
        
        if "versions" not in icon_info or "svg" not in icon_info["versions"]:
            continue

        if check_and_print(icon_name, "original"):
            continue
        if check_and_print(icon_name, "plain"):
            continue

        svg_versions = icon_info["versions"]["svg"]
        for svg_version in svg_versions:
            if check_and_print(icon_name, svg_version):
                break

    # A fallback default icon incase we don't have one.
    print("""
export { default as FallbackIcon } from "@primer/octicons/build/svg/code-16.svg";
    """.strip(' ').strip('\n'))

def gen_icon_jsx_elements():
    print_autogen_header()
    print("""
import * as LanguageIcons from "@/components/Icons/LanguageIcons";
import type { JSX } from "react";

export function getLangIcon(languageName: string): JSX.Element {
  switch(languageName) {
    """.strip(' ').strip('\n'))

    for language in supported_languages:
        lang_info = supported_languages[language]
        if 'devicon_name' not in lang_info:
            continue

        aliases = lang_info['alias']
        icon_name = lang_info['devicon_name']
        jsx_obj_name = icon_to_jsx(icon_name)

        for lang_class in [language] + aliases:
            print(f"""
    case "{lang_class}":
      return <LanguageIcons.{jsx_obj_name}/>;
            """.strip(' ').strip('\n'))

    print("""
    default:
      return <LanguageIcons.FallbackIcon/>;
  }
}
    """.strip(' ').strip('\n'))


if CONFIGS["gen_icon_variables"]:
    gen_icon_variables()
if CONFIGS["gen_icon_jsx_elements"]:
    gen_icon_jsx_elements()

